import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { prisma } from "../src/lib/db";
import { GuildError, createGuild, joinGuild, updateGuild, leaveGuild, dissolveGuild, changeGuildRole, transferGuild, kickGuildMember, reviewGuildRequest, cancelGuildRequest, getGuild, listGuilds, guildLeaderboard, guildWeekStart } from "../src/lib/guilds";
import { GUILD_COOLDOWN_MS, type GuildInput } from "../src/lib/guild-rules";

async function main() {
  assert.equal(guildWeekStart(new Date("2026-03-29T12:00:00Z")).toISOString(), "2026-03-22T23:00:00.000Z");
  assert.equal(guildWeekStart(new Date("2026-10-25T12:00:00Z")).toISOString(), "2026-10-18T22:00:00.000Z");
  assert.equal(guildWeekStart(new Date("2026-11-01T23:30:00Z")).toISOString(), "2026-11-01T23:00:00.000Z");
  const stamp = randomUUID().slice(0, 8);
  const ids = Array.from({ length: 30 }, (_, i) => `guild-${stamp}-${i}`);
  const tags = new Set<string>();
  const input = (suffix: string, joinMode: "OPEN" | "REQUEST" = "OPEN"): GuildInput => {
    let tag: string;
    do { tag = randomUUID().slice(0, 4).toUpperCase(); } while (tags.has(tag));
    tags.add(tag);
    return { name: `Guilde ${stamp} ${suffix}`, tag, description: "Bannière de test", icon: "squads", joinMode };
  };
  await prisma.user.createMany({ data: ids.map((id) => ({ id, username: id, name: id, email: `${id}@test.local`, balance: 2000 })) });
  await prisma.currencyLedger.createMany({ data: ids.map((userId) => ({ userId, amount: 2000, reason: "ADMIN" as const })) });
  const now = new Date();
  try {
    await assert.rejects(createGuild(ids[0], { ...input("bad"), tag: "!" }), GuildError);
    await assert.rejects(createGuild(ids[0], { ...input("bad"), icon: "not-an-icon" }), GuildError);
    await prisma.user.update({ where: { id: ids[29] }, data: { balance: 999 } });
    await assert.rejects(createGuild(ids[29], input("poor")), GuildError);
    const g1input = input("open"); const g1 = await createGuild(ids[0], g1input, now);
    assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: ids[0] } })).balance, 1000);
    assert.equal(await prisma.currencyLedger.count({ where: { userId: ids[0], reason: "GUILD_CREATE", amount: -1000, refId: g1.id } }), 1);
    await assert.rejects(createGuild(ids[1], { ...input("duplicate"), name: g1.name.toUpperCase() }));
    await assert.rejects(createGuild(ids[1], { ...input("duplicate"), tag: g1.tag.toLowerCase() }));
    assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: ids[1] } })).balance, 2000, "Unicité : débit annulé");
    const g2input = input("request", "REQUEST"); const g2 = await createGuild(ids[1], g2input, now);
    const race = await Promise.allSettled([createGuild(ids[2], input("raceA")), createGuild(ids[2], input("raceB"))]);
    assert.equal(race.filter((r) => r.status === "fulfilled").length, 1);
    assert.equal(await prisma.currencyLedger.count({ where: { userId: ids[2], reason: "GUILD_CREATE" } }), 1);
    await joinGuild(ids[3], g1.id, now);
    await assert.rejects(joinGuild(ids[3], g2.id, now), GuildError);
    await assert.rejects(createGuild(ids[3], input("already")), GuildError);
    await leaveGuild(ids[3], g1.id, now);
    await assert.rejects(joinGuild(ids[3], g1.id, now), GuildError);
    await assert.rejects(createGuild(ids[3], input("cooldown"), now), GuildError);
    await joinGuild(ids[3], g1.id, new Date(now.getTime() + GUILD_COOLDOWN_MS));
    await joinGuild(ids[4], g1.id); await joinGuild(ids[5], g1.id);
    await assert.rejects(updateGuild(ids[5], g1.id, g1input), GuildError);
    await changeGuildRole(ids[0], g1.id, ids[4], "OFFICER");
    await assert.rejects(changeGuildRole(ids[4], g1.id, ids[5], "OFFICER"), GuildError);
    await updateGuild(ids[0], g1.id, { ...g1input, joinMode: "REQUEST" });
    await joinGuild(ids[6], g1.id);
    const request = await prisma.guildJoinRequest.findUniqueOrThrow({ where: { guildId_userId: { guildId: g1.id, userId: ids[6] } } });
    assert.equal((await getGuild(ids[5], g1.tag))!.requests.length, 0, "Demandes privées aux gestionnaires");
    await assert.rejects(reviewGuildRequest(ids[5], g1.id, request.id, true), GuildError);
    await assert.rejects(reviewGuildRequest(ids[1], g2.id, request.id, true), GuildError);
    await reviewGuildRequest(ids[4], g1.id, request.id, true);
    await assert.rejects(reviewGuildRequest(ids[4], g1.id, request.id, true), GuildError);
    await joinGuild(ids[7], g1.id);
    let req = await prisma.guildJoinRequest.findUniqueOrThrow({ where: { guildId_userId: { guildId: g1.id, userId: ids[7] } } });
    await reviewGuildRequest(ids[4], g1.id, req.id, false);
    await joinGuild(ids[7], g1.id); await cancelGuildRequest(ids[7], g1.id);
    assert.equal(await prisma.guildJoinRequest.count({ where: { userId: ids[7] } }), 0);
    await joinGuild(ids[7], g1.id);
    await joinGuild(ids[7], g2.id);
    req = await prisma.guildJoinRequest.findUniqueOrThrow({ where: { guildId_userId: { guildId: g2.id, userId: ids[7] } } });
    await reviewGuildRequest(ids[1], g2.id, req.id, true);
    assert.equal(await prisma.guildJoinRequest.count({ where: { userId: ids[7] } }), 0, "Adhésion annule les autres demandes");
    await assert.rejects(kickGuildMember(ids[4], g1.id, ids[0]), GuildError);
    await assert.rejects(kickGuildMember(ids[4], g1.id, ids[7]), GuildError);
    await assert.rejects(leaveGuild(ids[0], g1.id), GuildError);
    await transferGuild(ids[0], g1.id, ids[4]);
    assert.equal((await prisma.guild.findUniqueOrThrow({ where: { id: g1.id } })).ownerId, ids[4]);
    assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: ids[0] } })).guildRole, "MEMBER");
    await assert.rejects(dissolveGuild(ids[0], g1.id), GuildError);
    await changeGuildRole(ids[4], g1.id, ids[6], "OFFICER");
    await changeGuildRole(ids[4], g1.id, ids[0], "OFFICER");
    await assert.rejects(kickGuildMember(ids[0], g1.id, ids[6]), GuildError);
    await changeGuildRole(ids[4], g1.id, ids[6], "MEMBER");
    await kickGuildMember(ids[0], g1.id, ids[6], now);
    await assert.rejects(joinGuild(ids[6], g1.id, now), GuildError);
    // Capacité : 19 membres, deux entrées concurrentes pour la dernière place.
    await updateGuild(ids[1], g2.id, { ...g2input, joinMode: "OPEN" });
    await prisma.user.updateMany({ where: { id: { in: ids.slice(8, 25) } }, data: { guildId: g2.id } });
    assert.equal(await prisma.user.count({ where: { guildId: g2.id } }), 19);
    const last = await Promise.allSettled([joinGuild(ids[25], g2.id), joinGuild(ids[26], g2.id)]);
    assert.equal(last.filter((r) => r.status === "fulfilled").length, 1);
    assert.equal(await prisma.user.count({ where: { guildId: g2.id } }), 20);
    const foreign = ids[last[0].status === "rejected" ? 25 : 26];
    // Un joueur convoité par deux guildes ne peut rejoindre qu’une seule.
    await updateGuild(ids[4], g1.id, g1input);
    await kickGuildMember(ids[1], g2.id, ids[8]);
    const cross = await Promise.allSettled([joinGuild(foreign, g1.id), joinGuild(foreign, g2.id)]);
    assert.equal(cross.filter((r) => r.status === "fulfilled").length, 1);
    assert((await listGuilds(ids[0], stamp)).guilds.some((g) => g.id === g1.id));
    assert((await guildLeaderboard("collection")).some((g) => g.id === g1.id));
    const duel = await prisma.duel.create({ data: { challengerId: ids[0], opponentId: ids[1], winnerId: ids[0], status: "DONE", acceptDeadline: now, resolvedAt: now } });
    assert((await guildLeaderboard("duels", now)).some((g) => g.id === g1.id && g.score >= 1));
    await prisma.duel.update({ where: { id: duel.id }, data: { resolvedAt: new Date(guildWeekStart(now).getTime() - 1) } });
    assert.equal((await guildLeaderboard("duels", now)).find((g) => g.id === g1.id)!.score, 0);
    await dissolveGuild(ids[4], g1.id, now);
    assert.equal(await prisma.user.count({ where: { guildId: g1.id } }), 0);
    assert.equal((await prisma.user.findUniqueOrThrow({ where: { id: ids[0] } })).guildLeftAt!.getTime(), now.getTime());
    const alone = await prisma.user.findUniqueOrThrow({ where: { id: ids[2] } });
    await leaveGuild(ids[2], alone.guildId!, now);
    assert.equal(await prisma.guild.count({ where: { id: alone.guildId! } }), 0);
    console.log("✓ Guildes : validation, coût unique et rollback, adhésion, demandes, confidentialité, rôles, expulsion, transfert, dissolution, capacité et appartenance concurrentes, délai 24 h, classements et semaine Paris/DST.");
  } finally {
    await prisma.user.deleteMany({ where: { id: { in: ids } } });
  }
}
main().finally(() => prisma.$disconnect()).catch((error) => { console.error(error); process.exitCode = 1; });
